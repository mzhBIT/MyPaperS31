"""Rasterize the supplied Feather status SVGs to 48px 1bpp firmware assets.

Supports the M/A paths, lines and rounded rectangle used by these three SVGs.
Oversampling preserves round stroke ends; no runtime SVG or SD reads required.
"""
from pathlib import Path
import math
import re
import xml.etree.ElementTree as ET
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SCALE = 16  # 24-unit viewbox -> 384px -> 48px


def arc_points(x1, y1, rx, ry, rotation, large, sweep, x2, y2):
    # SVG endpoint-to-center conversion (these Feather paths have zero rotation).
    if rotation != 0:
        raise ValueError("Rotated arcs are not supported")
    dx, dy = (x1 - x2) / 2, (y1 - y2) / 2
    factor = max(1, math.sqrt(dx * dx / rx**2 + dy * dy / ry**2))
    rx, ry = rx * factor, ry * factor
    numerator = max(0, rx**2 * ry**2 - rx**2 * dy**2 - ry**2 * dx**2)
    denominator = rx**2 * dy**2 + ry**2 * dx**2
    sign = -1 if bool(large) == bool(sweep) else 1
    f = sign * math.sqrt(numerator / denominator) if denominator else 0
    cx, cy = f * rx * dy / ry + (x1 + x2) / 2, -f * ry * dx / rx + (y1 + y2) / 2
    start = math.atan2((y1 - cy) / ry, (x1 - cx) / rx)
    finish = math.atan2((y2 - cy) / ry, (x2 - cx) / rx)
    delta = (finish - start) % (2 * math.pi)
    if not sweep:
        delta -= 2 * math.pi
    return [(cx + rx * math.cos(start + delta * i / 64),
             cy + ry * math.sin(start + delta * i / 64)) for i in range(65)]


def rasterize(name):
    svg = ET.parse(ROOT / "Assets/feather" / f"{name}.svg").getroot()
    image = Image.new("L", (24 * SCALE, 24 * SCALE), 255)
    draw = ImageDraw.Draw(image)
    width = round(float(svg.get("stroke-width", "2")) * SCALE)

    def stroke(points):
        points = [(round(x * SCALE), round(y * SCALE)) for x, y in points]
        draw.line(points, fill=0, width=width, joint="curve")
        for x, y in (points[0], points[-1]):
            r = width / 2
            draw.ellipse((x - r, y - r, x + r, y + r), fill=0)

    for node in svg:
        tag = node.tag.split("}")[-1]
        if tag == "line":
            stroke([(float(node.get("x1")), float(node.get("y1"))),
                    (float(node.get("x2")), float(node.get("y2")))])
        elif tag == "rect":
            x, y, w, h, radius = [float(node.get(k, "0")) for k in ("x", "y", "width", "height", "rx")]
            draw.rounded_rectangle((x * SCALE, y * SCALE, (x + w) * SCALE, (y + h) * SCALE),
                                   radius=radius * SCALE, outline=0, width=width)
            # Pillow outlines inside a rectangle; SVG strokes are centered.
            # Draw the centered ring using outer and inner rounded rectangles.
            half = width / 2
            draw.rounded_rectangle((x*SCALE-half, y*SCALE-half, (x+w)*SCALE+half, (y+h)*SCALE+half),
                                   radius=radius*SCALE+half, fill=0)
            draw.rounded_rectangle((x*SCALE+half, y*SCALE+half, (x+w)*SCALE-half, (y+h)*SCALE-half),
                                   radius=max(0, radius*SCALE-half), fill=255)
        elif tag == "path":
            tokens = re.findall(r"[MmAa]|[-+]?(?:\d*\.\d+|\d+)", node.get("d"))
            if tokens[0] != "M" or tokens[3] not in ("a", "A") or len(tokens) != 11:
                raise ValueError(f"Unsupported Feather path: {node.get('d')}")
            x, y = map(float, tokens[1:3])
            rx, ry, rotation, large, sweep, end_x, end_y = map(float, tokens[4:])
            if tokens[3] == "a":
                end_x += x
                end_y += y
            stroke(arc_points(x, y, rx, ry, rotation, large, sweep, end_x, end_y))
        else:
            raise ValueError(f"Unsupported SVG element: {tag}")
    return image.resize((48, 48), Image.Resampling.LANCZOS)


def main():
    output = ["// Generated by tools/generate_home_status_icons.py; do not edit.",
              "#pragma once", "#include <cstdint>", "namespace home_status_icons {"]
    for name in ("wifi", "wifi-off", "battery"):
        image = rasterize(name)
        image.save(ROOT / "Assets" / f"home-status-{name}.png")
        data = bytearray(48 * 6)
        for y in range(48):
            for x in range(48):
                if image.getpixel((x, y)) < 192:
                    data[y * 6 + x // 8] |= 0x80 >> (x % 8)
        output.append(f"constexpr uint8_t {name.replace('-', '_')}[288] = {{")
        for start in range(0, len(data), 16):
            output.append("    " + ", ".join(f"0x{v:02X}" for v in data[start:start+16]) + ",")
        output.append("};")
    output.append("} // namespace home_status_icons")
    (ROOT / "main/ui/home_status_icons.h").write_text("\n".join(output) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
