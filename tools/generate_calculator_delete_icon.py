"""Prepare the Feather SVG for rasterization, then pack a 48px firmware icon.

Run without arguments, rasterize Assets/calculator-delete.svg to
Assets/calculator-delete-render.png at 150x150, then run with --pack.
"""
from pathlib import Path
import argparse
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--pack", action="store_true")
    args = parser.parse_args()
    if not args.pack:
        ET.register_namespace("", "http://www.w3.org/2000/svg")
        svg = ET.parse(ROOT / "Assets/feather/delete.svg").getroot()
        svg.set("width", "150")
        svg.set("height", "150")
        # 1.25 SVG units -> 2.5px at 48px; match the surrounding font better.
        svg.set("stroke-width", "1.25")
        ET.ElementTree(svg).write(ROOT / "Assets/calculator-delete.svg", encoding="utf-8", xml_declaration=True)
        return
    from PIL import Image
    rendered = Image.open(ROOT / "Assets/calculator-delete-render.png").convert("RGBA")
    if rendered.size != (150,150):
        raise ValueError("Expected a 150x150 rasterized SVG")
    white = Image.new("RGBA",rendered.size,"white")
    white.alpha_composite(rendered)
    icon = white.convert("L").resize((48,48),Image.Resampling.LANCZOS)
    icon.save(ROOT / "Assets/calculator-delete.png")
    data = bytearray(288)
    for y in range(48):
        for x in range(48):
            if icon.getpixel((x,y)) < 192:
                data[y*6+x//8] |= 0x80 >> (x%8)
    if not any(data) or all(v==255 for v in data):
        raise ValueError("Empty or solid icon")
    lines = ["// Generated by tools/generate_calculator_delete_icon.py; do not edit.",
             "#pragma once", '#include "ui/icon_bitmap_1bpp.h"',
             "namespace calculator_icons {", "constexpr uint8_t delete_data[288] = {"]
    for start in range(0,len(data),16):
        lines.append("    "+", ".join(f"0x{v:02X}" for v in data[start:start+16])+",")
    lines.extend(["};", "constexpr IconBitmap1bpp delete_icon = {delete_data,48,48,6,sizeof(delete_data),24,24};",
                  "} // namespace calculator_icons"])
    (ROOT / "main/ui/calculator_icons_1bpp.h").write_text("\n".join(lines)+"\n",encoding="utf-8")

if __name__ == "__main__":
    main()
