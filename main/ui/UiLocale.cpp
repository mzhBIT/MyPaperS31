esp_err_t init()
{
    s_language = Language::English;
    nvs_handle_t handle = 0;
    esp_err_t result = nvs_open(NVS_NAMESPACE, NVS_READONLY, &handle);
    if (result == ESP_ERR_NVS_NOT_FOUND) return ESP_OK;
    if (result != ESP_OK) return result;
    uint8_t stored = 0;
    result = nvs_get_u8(handle, NVS_KEY, &stored);
    nvs_close(handle);
    if (result == ESP_OK && valid(static_cast<Language>(stored))) {
        s_language = static_cast<Language>(stored);
        return ESP_OK;
    }
    return (result == ESP_ERR_NVS_NOT_FOUND || result == ESP_OK) ? ESP_OK : result;
}

Language get() { return s_language; }

esp_err_t set(Language language)
{
    if (!valid(language)) return ESP_ERR_INVALID_ARG;
    if (language == s_language) return ESP_OK;
    nvs_handle_t handle = 0;
    esp_err_t result = nvs_open(NVS_NAMESPACE, NVS_READWRITE, &handle);
    if (result != ESP_OK) return result;
    result = nvs_set_u8(handle, NVS_KEY, static_cast<uint8_t>(language));
    if (result == ESP_OK) result = nvs_commit(handle);
    nvs_close(handle);
    if (result == ESP_OK) {
        s_language = language;
        ++s_generation;
    }
    return result;
}

uint32_t generation() { return s_generation; }

const char *text(TextId id)
{
    const auto index = static_cast<size_t>(id);
    if (index >= static_cast<size_t>(TextId::Count)) return "";
    const Translation &value = kText[index];
    const char *selected = s_language == Language::SimplifiedChinese ? value.zh_hans
                         : s_language == Language::TraditionalChinese ? value.zh_hant : value.en;
    return selected && selected[0] ? selected : value.en;
}

