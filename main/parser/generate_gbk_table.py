#!/usr/bin/env python3
"""
Generate a GBK → Unicode lookup table as a C header file.

Uses Python's built-in codecs module (which includes the GBK codec via
the CP936 Windows code page) to produce a compact flat array.

Index scheme: (hi - 0x81) * 190 + (lo - 0x40 - (1 if lo > 0x7F else 0))
Covering:  hi ∈ [0x81, 0xFE]  (126 values)
           lo ∈ [0x40, 0x7E] ∪ [0x80, 0xFE]  (190 values)
Total: 126 × 190 = 23,940 entries → ~48 KB of uint16_t
"""

import codecs
import sys
import os

# GBK codec identity
CODEC_NAME = "gbk"

# Byte ranges
HI_START, HI_END = 0x81, 0xFE  # 126 values
LO_RANGES = [(0x40, 0x7E), (0x80, 0xFE)]  # gaps at 0x7F
ENTRIES_PER_ROW = sum(hi - lo + 1 for lo, hi in LO_RANGES)  # 190


def lo_to_offset(lo: int) -> int:
    """Convert second byte to 0-based column offset (0..189)."""
    if 0x40 <= lo <= 0x7E:
        return lo - 0x40
    if 0x80 <= lo <= 0xFE:
        return 63 + (lo - 0x80)
    return -1  # invalid


def generate_table():
    decoder = codecs.getdecoder(CODEC_NAME)
    rows = 0  # count non-empty rows
    entries = []
    unmapped = 0

    for hi in range(HI_START, HI_END + 1):
        row_mapped = 0
        for lo_start, lo_end in LO_RANGES:
            for lo in range(lo_start, lo_end + 1):
                raw = bytes([hi, lo])
                try:
                    text, _ = decoder(raw)
                    cp = ord(text) if text else 0
                except (UnicodeDecodeError, LookupError):
                    cp = 0
                if cp == 0:
                    unmapped += 1
                else:
                    row_mapped += 1
                entries.append(cp)
        if row_mapped > 0:
            rows += 1

    print(f"// Generated GBK→Unicode table")
    print(f"// Rows with mappings: {rows}/{HI_END - HI_START + 1}")
    print(f"// Total entries: {len(entries)}")
    print(f"// Unmapped code points: {unmapped}")
    print(f"// Table size: {len(entries) * 2} bytes")
    return entries


def write_header(entries, output_path):
    """Write the C header file with the lookup table."""
    guard = "GBK_UNICODE_TABLE_H_"
    array_name = "gbk_unicode_table"

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by generate_gbk_table.py — DO NOT EDIT */\n\n")
        f.write(f"#ifndef {guard}\n")
        f.write(f"#define {guard}\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("/* GBK → Unicode mapping table.\n")
        f.write(" * Index: (hi - 0x81) * 190 + (lo - 0x40 - (lo > 0x7F ? 1 : 0))\n")
        f.write(" *   hi ∈ [0x81, 0xFE],  lo ∈ [0x40, 0x7E] ∪ [0x80, 0xFE]\n")
        f.write(" * 0x0000 = unmapped code point\n")
        f.write(f" * Size: {len(entries)} entries × 2 bytes = {len(entries) * 2} bytes\n")
        f.write(" */\n\n")
        f.write(f"static const uint16_t {array_name}[{len(entries)}] = {{\n")

        # Pretty-print 16 values per line
        for i in range(0, len(entries), 16):
            chunk = entries[i : i + 16]
            hex_vals = ", ".join(f"0x{u:04X}" for u in chunk)
            f.write(f"    {hex_vals}")
            if i + 16 < len(entries):
                f.write(",")
            f.write("\n")

        f.write("};\n\n")
        f.write(f"/* Offset helper */\n")
        f.write("static inline int gbk_table_index(uint8_t hi, uint8_t lo) {\n")
        f.write("    if (hi < 0x81 || hi > 0xFE || lo < 0x40 || lo == 0x7F || lo > 0xFE)\n")
        f.write("        return -1;\n")
        f.write("    int col = lo > 0x7F ? (lo - 0x40 - 1) : (lo - 0x40);\n")
        f.write("    return (hi - 0x81) * 190 + col;\n")
        f.write("}\n\n")
        f.write(f"#endif /* {guard} */\n")

    print(f"Wrote {output_path}")


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    output_path = os.path.join(script_dir, "gbk_unicode_table.h")

    print(f"Generating GBK→Unicode table...", file=sys.stderr)
    entries = generate_table()
    write_header(entries, output_path)
    print(f"Done. {len(entries)} entries → {output_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
